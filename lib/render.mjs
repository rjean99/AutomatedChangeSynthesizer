// Markdown rendering for the three output targets (pull request, Jira ticket,
// CHANGELOG.md entry) plus in-place CHANGELOG.md maintenance.

import { existsSync, readFileSync, writeFileSync } from "node:fs";

export const BUCKETS = [
  { id: "breaking", title: "⚠️ Breaking Changes", ai: "breaking" },
  { id: "features", title: "✨ Features & Functional Updates", ai: "features" },
  { id: "fixes", title: "🐛 Bug Fixes & Refactoring", ai: "fixes" },
  { id: "infra", title: "📦 Dependency Updates & Infrastructure Changes", ai: "infrastructure" },
];
const QUALITY = { id: "quality", title: "🧪 Tests & Documentation" };

export function code(s) {
  if (s == null) return "";
  const str = String(s);
  return str.includes("`") ? `\`\` ${str} \`\`` : `\`${str}\``;
}

const plural = (n, word) => `${n} ${word}${n === 1 ? "" : "s"}`;

function statusWord(f) {
  if (f.untracked) return "added (untracked)";
  return { A: "added", M: "modified", D: "deleted", R: `renamed from ${code(f.oldPath)}`, C: `copied from ${code(f.oldPath)}`, T: "type changed" }[f.status] || f.status;
}

// ───────────────────────── shared sections ─────────────────────────

function renderHeader(a) {
  const t = a.totals;
  const title = a.mode === "staged" ? `Staged changes vs ${code("HEAD")}` : `${code(a.branch)} → ${code(a.base)}`;
  const meta = a.mode === "staged"
    ? `staged against \`${a.mergeBase}\``
    : `merge-base \`${a.mergeBase}\`${a.head ? ` · head \`${a.head}\`` : ""}`;
  const mix = Object.entries(t.byClass).sort((x, y) => y[1] - x[1]).map(([k, n]) => `${n} ${k}`).join(" · ");
  return [
    `# Change summary: ${title}`,
    "",
    `> Generated by prnotes ${a.tool.version} on ${a.generatedAt.slice(0, 10)} · ${meta}`,
    "",
    "| Files | Insertions | Deletions | Commits | Modules |",
    "|---:|---:|---:|---:|---:|",
    `| ${t.files} | +${t.insertions} | −${t.deletions} | ${a.commits.length} | ${a.architecture.modulesTouched} |`,
    "",
    `**Change mix:** ${mix || "no changes"}`,
    "",
  ];
}

function deterministicOverview(a) {
  const b = a.buckets;
  const api = a.architecture.publicApi.reduce((acc, x) => ({ added: acc.added + x.added, removed: acc.removed + x.removed, changed: acc.changed + x.changed }), { added: 0, removed: 0, changed: 0 });
  const hot = a.architecture.hotspots[0];
  const scope = a.mode === "staged" ? "The staged changes touch" : "This branch touches";
  const parts = [
    `${scope} ${plural(a.totals.files, "file")} across ${plural(a.architecture.modulesTouched, "module")}${a.commits.length ? ` in ${plural(a.commits.length, "commit")}` : ""}.`,
    `Public API: ${api.added} added, ${api.removed} removed, ${api.changed} changed.`,
    b.breaking.length ? `**${plural(b.breaking.length, "potentially breaking change")} detected.**` : "No breaking changes detected.",
  ];
  if (hot) parts.push(`Most activity is in ${code(hot.area)} (${hot.share}% of changed lines).`);
  return parts.join(" ");
}

function renderArchitecture(a, ai) {
  const arch = a.architecture;
  const out = [];
  if (ai?.architecture?.length) out.push(...ai.architecture.map((s) => `- ${s}`));
  if (arch.hotspots.length) out.push(`- **Hotspots:** ${arch.hotspots.map((h) => `${code(h.area)} ${h.share}%`).join(" · ")}`);
  if (arch.newModules.length) out.push(`- **New modules:** ${arch.newModules.map(code).join(", ")}`);
  if (arch.removedModules.length) out.push(`- **Removed modules:** ${arch.removedModules.map(code).join(", ")}`);
  for (const e of arch.coupling) {
    out.push(`- **${e.change === "added" ? "New dependency" : "Dropped dependency"}:** ${code(e.from)} → ${code(e.to)} (via ${e.files.map(code).join(", ")})`);
  }
  if (arch.publicApi.length) {
    out.push(`- **Public API surface:** ${arch.publicApi.map((x) => `${code(x.area)} +${x.added} / −${x.removed} / ~${x.changed}`).join(" · ")}`);
  }
  const extAdded = arch.externals.filter((e) => e.change === "added");
  const extRemoved = arch.externals.filter((e) => e.change === "removed");
  if (extAdded.length) out.push(`- **New third-party imports:** ${extAdded.map((e) => `${code(e.pkg)} (${e.files.map(code).join(", ")})`).join("; ")}`);
  if (extRemoved.length) out.push(`- **Third-party imports dropped:** ${extRemoved.map((e) => code(e.pkg)).join(", ")}`);
  if (!out.length) return [];
  return ["## 🏗️ Architecture impact", "", ...out, ""];
}

function refsLine(item) {
  const r = item.refs;
  if (!r) return null;
  const what = r.member ? `call sites of ${code("." + r.name + "(")}` : `references to ${code(r.name)}`;
  if (!r.count) return `no remaining ${what} found in the repo`;
  return `${plural(r.count, "possible " + (r.member ? "call site" : "reference"))} still to review (${what} in ${plural(r.files.length, "file")}): ${r.sample.map(code).join(", ")}${r.count > r.sample.length ? " ..." : ""}`;
}

function itemLines(item, { evidence = true } = {}) {
  const pathNote = item.path && !item.text.includes(code(item.path)) ? ` · ${code(item.path)}` : "";
  const lines = [`- ${item.text}${pathNote}`];
  if (evidence) {
    if (item.hint) lines.push(`  - ↳ ${item.hint}`);
    const r = refsLine(item);
    if (r) lines.push(`  - ↳ ${r}`);
  }
  return lines;
}

function renderItems(items, opts) {
  const areas = [...new Set(items.map((i) => i.area))];
  if (items.length <= 6 || areas.length < 2) return items.flatMap((i) => itemLines(i, opts));
  const out = [];
  for (const area of areas) {
    out.push(`**${area ? code(area) : "Repository-wide"}**`, "");
    out.push(...items.filter((i) => i.area === area).flatMap((i) => itemLines(i, opts)), "");
  }
  return out;
}

function relatedCommits(a, bucketId) {
  const cs = a.buckets.related[bucketId] || [];
  if (!cs.length) return [];
  return ["", `*Related commits:* ${cs.map((c) => `${c.scope ? `**${c.scope}:** ` : ""}${c.description} (${code(c.short)})`).join(" · ")}`];
}

function aiEntryLines(e) {
  const files = e.files?.length ? ` (${e.files.map(code).join(", ")})` : "";
  return [`- **${e.summary}**${e.impact ? `: ${e.impact}` : ""}${files}`];
}

function renderBucket(a, ai, bucket, { level = "##", html = true, empty = true } = {}) {
  const det = a.buckets[bucket.id];
  const aiEntries = ai ? ai[bucket.ai] || [] : null;
  const has = aiEntries ? aiEntries.length || det.length : det.length;
  if (!has && !empty) return [];
  const out = [`${level} ${bucket.title}`, ""];
  if (!has) return [...out, "_None detected._", ""];
  if (aiEntries) {
    out.push(...(aiEntries.length ? aiEntries.flatMap(aiEntryLines) : ["_None identified in the narrative; see static analysis._"]));
    if (det.length && html) {
      out.push("", `<details><summary>Static analysis evidence (${det.length})</summary>`, "", ...renderItems(det), "", "</details>");
    }
  } else {
    out.push(...renderItems(det));
  }
  out.push(...relatedCommits(a, bucket.id), "");
  return out;
}

function renderFlags(a, ai) {
  const out = [];
  if (ai?.reviewer_focus?.length) out.push("**Where to focus**", "", ...ai.reviewer_focus.map((s) => `- ${s}`), "");
  if (a.flags.length) {
    const groups = new Map();
    for (const f of a.flags) {
      if (!groups.has(f.label)) groups.set(f.label, []);
      groups.get(f.label).push(f);
    }
    const priority = ["secret", "focus", "migration", "sensitive", "debug", "infra", "ci", "untested", "skip", "suppress", "large", "todo"];
    const sorted = [...groups].sort((x, y) => priority.indexOf(x[1][0].id) - priority.indexOf(y[1][0].id));
    for (const [label, fs] of sorted) {
      out.push(`- **${label}** (${fs.length})`);
      for (const f of fs.slice(0, 12)) out.push(`  - ${code(f.line ? `${f.path}:${f.line}` : f.path)}${f.detail ? `: ${f.detail}` : ""}`);
      if (fs.length > 12) out.push(`  - ...and ${fs.length - 12} more`);
    }
    out.push("");
  }
  return out.length ? ["## 🔍 Review notes", "", ...out] : [];
}

function symbolLine(c) {
  const k = c.sym.kind;
  const name = code(c.sym.label || c.sym.qname);
  const vis = c.sym.pub === false ? " (internal)" : "";
  const hint = c.hint ? `; ${c.hint}` : "";
  switch (c.type) {
    case "added": return `**Added** ${k} ${name}${vis}: ${code(c.sym.signature)}${hint}`;
    case "removed": return `**Removed** ${k} ${name}${vis}`;
    case "modified": {
      const delta = c.sym.lineCount - c.old.lineCount;
      const what = ["class", "interface", "type", "struct", "enum", "trait", "record", "object"].includes(k) ? "definition" : "implementation";
      return `**Changed** ${what} of ${k} ${name}${vis} (${c.sym.lineCount} lines${delta ? `, ${delta > 0 ? "+" : ""}${delta}` : ""})${hint}`;
    }
    case "signature": return (c.compatible
      ? `**Extended** ${k} ${name}${vis} with optional parameter(s): ${code(c.old.signature)} → ${code(c.sym.signature)}`
      : `**Signature changed** ${k} ${name}${vis}: ${code(c.old.signature)} → ${code(c.sym.signature)}`) + hint;
    case "renamed": return `**Renamed** ${k} ${code(c.old.qname)} → ${name} (body unchanged)`;
    case "moved": return c.edited
      ? `**Moved & modified** ${k} ${name} here from ${code(c.from)}: ${code(c.old.signature)} → ${code(c.sym.signature)}`
      : `**Moved** ${k} ${name} here from ${code(c.from)} (body unchanged)`;
    case "moved-out": return `**Moved** ${k} ${name} to ${code(c.to)}`;
    default: return `${c.type} ${name}`;
  }
}

function renderFileDetail(a, { html }) {
  const out = html ? ["<details><summary>Per-file analysis</summary>", ""] : ["## Files changed", ""];
  for (const f of [...a.files].sort((x, y) => x.path.localeCompare(y.path))) {
    if (f.cls === "lockfile") continue;
    const stats = f.binary ? "binary" : `+${f.insertions} −${f.deletions}`;
    out.push(`- ${code(f.path)}: ${statusWord(f)} · ${f.cls}${f.lang ? ` · ${f.lang}` : ""} · ${stats}`);
    for (const c of f.symbols) out.push(`  - ${symbolLine(c)}`);
    if (f.imports.added.length) out.push(`  - Imports added: ${f.imports.added.map((i) => code(i.spec)).join(", ")}`);
    if (f.imports.removed.length) out.push(`  - Imports removed: ${f.imports.removed.map((i) => code(i.spec)).join(", ")}`);
    if (!f.symbols.length && f.hunkContexts.length && f.status === "M") out.push(`  - Touched regions: ${f.hunkContexts.slice(0, 6).map(code).join(", ")}`);
  }
  out.push("");
  if (html) out.push("</details>", "");
  return out;
}

function renderCommitLog(a, { html }) {
  if (!a.commits.length) return [];
  const list = a.commits.map((c) => `- ${code(c.short)} ${c.subject} - ${c.author}`);
  return html ? ["<details><summary>Commit log</summary>", "", ...list, "", "</details>", ""] : ["## Commits", "", ...list, ""];
}

// ───────────────────────── targets ─────────────────────────

export function renderPR(a, ai, { html = true } = {}) {
  if (!a.files.length) return [...renderHeader(a), "_No changes to report._", ""].join("\n");
  return [
    ...renderHeader(a),
    "## Overview", "", ai?.overview || deterministicOverview(a), "",
    ...renderArchitecture(a, ai),
    ...BUCKETS.flatMap((b) => renderBucket(a, ai, b, { html })),
    ...renderBucket(a, null, QUALITY, { html, empty: false }),
    ...renderFlags(a, ai),
    ...renderFileDetail(a, { html }),
    ...renderCommitLog(a, { html }),
  ].join("\n");
}

// Jira's editor converts pasted Markdown but drops raw HTML, so no <details>.
export function renderJira(a, ai) {
  return renderPR(a, ai, { html: false });
}

export function renderRelease(a, ai, label) {
  const out = [`## [${label}] - ${a.generatedAt.slice(0, 10)}`, ""];
  if (ai?.overview) out.push(ai.overview, "");
  for (const b of BUCKETS) {
    const entries = ai ? ai[b.ai] || [] : a.buckets[b.id];
    if (!entries.length) continue;
    out.push(`### ${b.title}`, "");
    out.push(...entries.flatMap((e) => (ai ? aiEntryLines(e) : itemLines(e, { evidence: false }))), "");
  }
  if (out.length === 2) out.push("_No notable changes._", "");
  return out.join("\n");
}

const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// Insert (or replace) the `## [label]` section, keeping the file's preamble and older releases.
export function updateChangelog(file, entry, label) {
  const preamble = "# Changelog\n\nAll notable changes to this project are documented in this file.\n";
  let text = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : preamble;
  const section = new RegExp(`^## \\[${escapeRe(label)}\\][^\\n]*\\n[\\s\\S]*?(?=^## |(?![\\s\\S]))`, "m");
  const body = entry.trimEnd() + "\n\n";
  if (section.test(text)) {
    text = text.replace(section, () => body);
  } else {
    const idx = text.search(/^## /m);
    text = idx === -1 ? `${text.trimEnd()}\n\n${body}` : text.slice(0, idx) + body + text.slice(idx);
  }
  writeFileSync(file, text.trimEnd() + "\n");
}
